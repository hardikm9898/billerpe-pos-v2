// Regenerates src/lib/routePermissions.ts from the exe's own table
// (billerpe-local-exe/constant/routePermissions.js), so the Web POS refuses
// an action with a clear message before sending it, exactly where the exe
// would. Run after changing that file:
//   node scripts/sync-route-permissions.cjs
const fs = require("fs");
const path = require("path");
const source = path.resolve(__dirname, "../../billerpe-local-exe/constant/routePermissions.js");
const { ROUTE_PERMISSIONS, ANY } = require(source);
const rules = Object.entries(ROUTE_PERMISSIONS)
  .filter(([, rule]) => rule !== ANY)
  .map(([key, rule]) => `  ${JSON.stringify(key)}: ${JSON.stringify(rule)},`)
  .join("\n");
const out = `// GENERATED by scripts/sync-route-permissions.cjs from
// billerpe-local-exe/constant/routePermissions.js - do not edit by hand.
// Every exe route that needs a permission: [module, action, special?].
// Routes open to any staff member are simply not listed.
import type { PermissionModule, SpecialPermission, StandardAction } from "@/mock/types";

export type RouteRule = [PermissionModule, StandardAction, SpecialPermission?];

export const ROUTE_PERMISSIONS: Record<string, RouteRule> = {
${rules}
};
`;
fs.writeFileSync(path.resolve(__dirname, "../src/lib/routePermissions.ts"), out);
console.log(`wrote ${Object.keys(ROUTE_PERMISSIONS).length} routes (${rules.split("\n").length} gated)`);

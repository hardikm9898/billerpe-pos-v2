/** Bumps a "hh:mm am/pm" label forward by `mins` minutes, wrapping across noon/midnight. */
function addMinutes(time: string, mins: number): string {
  const m = time.match(/(\d{1,2}):(\d{2})\s?(am|pm)/i)!;
  let h = Number(m[1]) % 12;
  if ((m[3] ?? "").toLowerCase() === "pm") h += 12;
  const total = (((h * 60 + Number(m[2]) + mins) % 1440) + 1440) % 1440;
  const hh = Math.floor(total / 60);
  const mm = total % 60;
  const ap = hh >= 12 ? "pm" : "am";
  return `${`${hh % 12 || 12}`.padStart(2, "0")}:${`${mm}`.padStart(2, "0")} ${ap}`;
}

function settled(
  id: string,
  orderNo: number,
  tableLabel: string,
  total: number,
  mode: NonNullable<Order["paymentMode"]>,
  businessDate: string,
  type: Order["type"] = "Dine In",
  lines: Order["lines"] = [],
  time = "08:12 pm",
): Order {
  return {
    id,
    orderNo,
    type,
    tableLabel,
    guests: 2,
    status: "Settled",
    kotRounds: 1,
    lines,
    payments:
      mode === "Split"
        ? [
            { mode: "Cash", amount: 500 },
            { mode: "UPI", amount: total - 500 },
          ]
        : [{ mode: mode as never, amount: total }],
    paymentMode: mode,
    businessDate,
    createdAt: `${businessDate} ${time}`,
    settledAt: `${businessDate} ${addMinutes(time, 45)}`,
    createdBy: "Hardik Makwana",
    itemised: lines.length > 0,
    fallbackTotal: total,
  };
}


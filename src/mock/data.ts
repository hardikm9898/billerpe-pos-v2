function skuFor(name: string, id: string) {
  const initials = name
    .split(/\s+/)
    .map((w) => w[0])
    .join("")
    .toUpperCase()
    .slice(0, 3);
  const num = id.replace(/\D/g, "").padStart(2, "0");
  return `${initials}${num}`;
}

function item(
  id: string,
  name: string,
  categoryId: string,
  price: number,
  extra: Partial<MenuItem> = {},
): MenuItem {
  return {
    id,
    name,
    categoryId,
    price,
    favourite: false,
    active: true,
    veg: true,
    sku: skuFor(name, id),
    ...extra,
  };
}

